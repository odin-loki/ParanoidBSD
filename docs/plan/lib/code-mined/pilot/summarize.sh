#!/bin/bash
# summarize.sh   Regenerates every number of the pilot report from the unit result files. Output: $OUT (default pilot/data/summary.md) + results.tsv (one row per function).
# results.tsv columns: N name kind class label status level nresolved A B vac wp_secs cause resolved | annot: attempts final tokens_in tokens_out usd_cons usd_listed annot_secs | total_secs
D=${PILOT_DATA:-/mnt/c/ParanoidBSD/mined-data/pilot}; HERE=$(cd "$(dirname "$0")" && pwd); OUTD=${OUTD:-$HERE/data}; mkdir -p "$OUTD"; U=$D/units
R=$OUTD/results.tsv; : >"$R"
for d in "$U"/u*; do
  [ -f "$d/result.tsv" ] || continue
  IFS=$'\t' read -r N name kind cls st level nres ap at bp bt vac secs cause resolved <"$d/result.tsv"
  an="-	-	0	0	0	0	0"; [ -f "$d/annot.tsv" ] && an=$(cut -f2- "$d/annot.tsv")
  asecs=$(echo "$an" | cut -f7); tot=$(awk -v a="$secs" -v b="${asecs:-0}" 'BEGIN{printf "%.1f", a+b}')
  # label per SELLABLE_PLAN section 1: PROVED needs nothing assumed beyond the stated contract; names resolved from other headers or a pointer precondition make it PROVED-ASSUMING
  label="not-proved"; real=$(grep -c . "$d/fn.c" 2>/dev/null)
  sigptr=$(head -3 "$d/fn.c" 2>/dev/null | tr '\n' ' ' | sed -E 's/\{.*//' | grep -c '\*')
  if [ "$st" = PROVED ]; then
    if [ "${nres:-0}" -gt 0 ] || [ "$cls" = ptr ] || [ "$sigptr" -gt 0 ]; then label=PROVED-ASSUMING; else label=PROVED; fi
  fi
  [ "$(cut -f2 "$d/annot.tsv" 2>/dev/null)" != "" ] || true
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$N" "$name" "$kind" "$cls" "$label" "$st" "$level" "${nres:-0}" "$ap/$at" "$bp/$bt" "$vac" "$secs" "$cause" "$resolved" "$an" "$tot" "$sigptr" >>"$R"
done
sort -n -o "$R" "$R"
stats() { sort -n | awk '{a[NR]=$1; s+=$1} END{ if(NR==0){print "n=0"; exit} m=(NR%2? a[(NR+1)/2] : (a[NR/2]+a[NR/2+1])/2); printf "n=%d mean=%.4f median=%.4f p90=%.4f max=%.4f", NR, s/NR, m, a[int(0.9*NR+0.9999)], a[NR] }'; }
{
echo "# Pilot summary (generated by summarize.sh from committed data; do not edit by hand)"
echo
echo "Functions in sample: $(wc -l <"$R")"
echo
echo "## Final label (SELLABLE_PLAN section 1)"; echo '```'; cut -f5 "$R" | sort | uniq -c | sort -rn; echo '```'
echo "## Status of the Frama-C WP run (after annotation attempts)"; echo '```'; cut -f6 "$R" | sort | uniq -c | sort -rn; echo '```'
echo "## By kind: label counts"; echo '```'
awk -F'\t' '{k[$3]++; l[$3 " " $5]++} END{for (x in l) print x, l[x]}' "$R" | sort | awk '{printf "%-16s %-16s %s\n", $1, $2, $3}'
echo '```'
echo "## By kind: proved (PROVED + PROVED-ASSUMING) / total"; echo '```'
awk -F'\t' '{t[$3]++; if ($5 ~ /^PROVED/) p[$3]++} END{for (k in t) printf "%-16s %d / %d  (%.0f%%)\n", k, p[k]+0, t[k], 100*(p[k]+0)/t[k]}' "$R" | sort
echo '```'
echo "## By class (contract mentions pointers/fields = ptr)"; echo '```'
awk -F'\t' '{t[$4]++; if ($5 ~ /^PROVED/) p[$4]++} END{for (k in t) printf "%-8s %d / %d proved\n", k, p[k]+0, t[k]}' "$R" | sort; echo '```'
echo "## Why not proved (cause of the final status)"; echo '```'
awk -F'\t' '$5=="not-proved"{c=$13; gsub(/[0-9]+/,"N",c); sub(/unresolved symbol: .*/,"unresolved symbol (macro/enum/variable from a header not found, or ambiguous)",c); print $6 ": " c}' "$R" | sort | uniq -c | sort -rn | head -30
echo '```'
echo "## Wall time per function, seconds (Frama-C WP phases + annotation attempts)"; echo '```'
echo "all:         $(cut -f22 "$R" | stats)"
echo "proved:      $(awk -F'\t' '$5 ~ /^PROVED/{print $22}' "$R" | stats)"
echo "not-proved:  $(awk -F'\t' '$5=="not-proved"{print $22}' "$R" | stats)"
for k in $(cut -f3 "$R" | sort -u); do echo "$k: $(awk -F'\t' -v k=$k '$3==k{print $22}' "$R" | stats)"; done
echo '```'
echo "## Model tokens and USD (GLM-5.3-Flash via Morph; only FAILED functions with a loop/goal left were sent to the model)"
echo; echo "Functions sent to the model: $(awk -F'\t' '$17>0' "$R" | wc -l), PROVED by that route: $(awk -F'\t' '$16=="PROVED"' "$R" | wc -l)"
echo "Ledger: $(wc -l <"$D/morph_ledger.tsv") calls (incl. the smoke test); USD at the conservative price $(awk -F'\t' '{s+=$8} END{printf "%.4f", s}' "$D/morph_ledger.tsv"); at Morph's listed price $(awk -F'\t' '{s+=$9} END{printf "%.4f", s}' "$D/morph_ledger.tsv")"
echo '```'
echo "USD per function (conservative price), over ALL sampled functions (most cost 0):  $(awk -F'\t' '{print $19}' "$R" | stats)"
echo "USD per function, over the functions sent to the model only:                      $(awk -F'\t' '$17>0{print $19}' "$R" | stats)"
echo "tokens in per sent function:  $(awk -F'\t' '$17>0{print $17}' "$R" | stats)"
echo "tokens out per sent function: $(awk -F'\t' '$17>0{print $18}' "$R" | stats)"
for k in $(cut -f3 "$R" | sort -u); do echo "USD $k (all of kind): $(awk -F'\t' -v k=$k '$3==k{print $19}' "$R" | stats)"; done
echo '```'
} >"$OUTD/summary.md"
cat "$OUTD/summary.md"
