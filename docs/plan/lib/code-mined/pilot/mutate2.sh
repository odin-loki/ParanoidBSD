#!/bin/bash
# mutate2.sh <rundir> [P]   Mutation test of every proved unit of a run (round 3: WP proofs AND CBMC bit-vector proofs): break the C code of the target function in one place and
# require the proof to FAIL on the unchanged contract.
# Mutants (first applicable occurrence inside the target function only): eq (== -> !=), lt (< -> <=), gt (> -> >=), and (&& -> ||), add (+ -> -), band (& -> |), shl (<< -> >>), ret (return 0 <-> 1).
# WP unit:   KILLED if WP no longer proves all contract goals (A run, -@terminates);  KILLED-UB if the contract still holds but WP no longer proves the run-time-error goals.
# CBMC unit: KILLED if cbmc reports a failure of the harness assertion; KILLED-UB if only an undefined-behaviour check fails; survivors stay "survived".
# A survivor is an equivalent mutant or a contract too weak to see the change. Writes <unit>/mutation.tsv (N op result) and <rundir>/mutation_summary.tsv.
HERE=$(cd "$(dirname "$0")" && pwd); R=$1; P=${2:-6}
one() {
  d=$1; . "$HERE/env.sh"
  st=$(cut -f5 "$d/result.tsv" 2>/dev/null); bvs=$(cut -f4 "$d/result.bv.tsv" 2>/dev/null)
  if [ "$st" = PROVED ]; then eng=WP; src=$d/unit.final.c
  elif [ "$bvs" = BV-PROVED ]; then eng=CBMC; src=$d/bv.h.c
  else exit 0; fi
  [ -f "$d/mutation.tsv" ] && exit 0
  IFS=$'\t' read -r N name rest <"$d/result.tsv"; MD=$(cat "$d/machdep" 2>/dev/null || echo gcc_x86_64)
  U_=$(sed -n 's/.*unwind=\([0-9]*\).*/\1/p' "$d/result.bv.tsv" 2>/dev/null | head -1); [ -z "$U_" ] && U_=2
  : >"$d/mutation.tsv.part"
  for op in eq lt gt and add band shl ret; do
    W=$(mktemp -d)
    awk -v n="$name" -v op="$op" '
      { L[NR] = $0 } END {
        s = 0; e = NR
        for (i = 1; i <= NR; i++) { if (!s && match(L[i], "(^|[^A-Za-z0-9_])" n "[ \t]*\\(") && L[i] !~ /;[ \t]*$/) s = i; if (L[i] ~ /bit-vector harness generated by acsl2bv/) { e = i - 1; break } }
        # only from the line of the body brace on (the head may contain == in attributes)
        b = 0; for (i = s; i <= e && s > 0; i++) if (index(L[i], "{")) { b = i; break }
        done = 0
        for (i = 1; i <= NR; i++) {
          t = L[i]
          if (b > 0 && i >= b && i <= e && !done && t !~ /^[ \t]*(\/\*|\*|\/\/)/) {
            if (op == "eq" && sub(/==/, "!=", t)) done = 1
            else if (op == "lt" && match(t, /[^<]<[^<=]/)) { t = substr(t, 1, RSTART) "<=" substr(t, RSTART + 2); done = 1 }
            else if (op == "gt" && match(t, /[^>-]>[^>=]/)) { t = substr(t, 1, RSTART) ">=" substr(t, RSTART + 2); done = 1 }
            else if (op == "and" && sub(/&&/, "||", t)) done = 1
            else if (op == "add" && match(t, /[A-Za-z0-9_)\] ] ?\+ ?[A-Za-z0-9_(]/)) { p = index(substr(t, RSTART), "+") + RSTART - 1; if (substr(t, p - 1, 1) != "+" && substr(t, p + 1, 1) != "+") { t = substr(t, 1, p - 1) "-" substr(t, p + 1); done = 1 } }
            else if (op == "band" && match(t, /[^&]&[^&=]/) && t !~ /&[A-Za-z_]+[ ]*[,)]/) { t = substr(t, 1, RSTART) "|" substr(t, RSTART + 2); done = 1 }
            else if (op == "shl" && sub(/<</, ">>", t)) done = 1
            else if (op == "ret" && sub(/return \(?0L?\)?;/, "return 1;", t)) done = 1
            else if (op == "ret" && sub(/return \(?1L?\)?;/, "return 0;", t)) done = 1
          }
          print t
        }
        if (!done) print "NOMUTANT" > "/dev/stderr"
      }' "$src" >"$W/m.c" 2>"$W/err"
    if grep -q NOMUTANT "$W/err" || cmp -s "$src" "$W/m.c"; then rm -rf "$W"; continue; fi
    cd "$W"
    if [ $eng = WP ]; then
      cnt() { sed -n 's/.*Proved goals: *\([0-9]*\) *\/ *\([0-9]*\).*/\1 \2/p' | tail -1; }
      pa=$(timeout 300 frama-c -kernel-warn-key annot-error=active -machdep $MD -wp -wp-no-rte -wp-prop=-@terminates -wp-cache none -wp-timeout 10 -wp-prover alt-ergo,z3,cvc5 -wp-fct "$name" m.c 2>&1 | cnt)
      if [ -z "$pa" ]; then r=invalid; elif [ "${pa% *}" != "${pa#* }" ]; then r=killed
      else pb=$(timeout 300 frama-c -kernel-warn-key annot-error=active -machdep $MD -wp -wp-rte -wp-prop=-@terminates -wp-cache none -wp-timeout 10 -wp-prover alt-ergo,z3,cvc5 -wp-fct "$name" m.c 2>&1 | cnt)
           if [ -n "$pb" ] && [ "${pb% *}" != "${pb#* }" ]; then r=killed-ub; else r=survived; fi; fi
    else
      out=$(timeout 300 cbmc m.c --function main --unwind $U_ --unwinding-assertions --object-bits 12 2>&1)
      if echo "$out" | grep -q "VERIFICATION SUCCESSFUL"; then
        outb=$(timeout 300 cbmc m.c --function main --unwind $U_ --unwinding-assertions --object-bits 12 --pointer-check --bounds-check --signed-overflow-check --div-by-zero-check --undefined-shift-check 2>&1)
        if echo "$outb" | grep -q "VERIFICATION FAILED"; then r=killed-ub; else r=survived; fi
      elif echo "$out" | grep -q "VERIFICATION FAILED"; then r=killed
      else r=invalid; fi
    fi
    printf '%s\t%s\t%s\t%s\n' "$N" "$op" "$r" "$eng" >>"$d/mutation.tsv.part"
    cd /; rm -rf "$W"
  done
  mv "$d/mutation.tsv.part" "$d/mutation.tsv"
}
export -f one; export HERE
ls -d "$R"/u* | xargs -P "$P" -I{} bash -c 'one {}'
cat "$R"/u*/mutation.tsv 2>/dev/null >"$R/mutation_summary.tsv"
echo "mutants by result (engine, result):"; cut -f3,4 "$R/mutation_summary.tsv" | sort | uniq -c
echo "units with at least one mutant: $(ls "$R"/u*/mutation.tsv 2>/dev/null | wc -l); units with a surviving mutant: $(grep -l survived "$R"/u*/mutation.tsv 2>/dev/null | wc -l)"
