#!/usr/bin/env python3
"""dsv_prompt.py   stdin: one manual-packet record (jsonl line). stdout: the chat-completions request for morph-dsv41flash-1017.
Gives the model, per record: the slice, the failure history of every listed function and, when the slice does not contain the whole function
(head or tail cut, or a macro-generated function), the full function source from the real file (macro definition too, when found in that file)."""
import json, re, sys, os

MAXFULL = 14000      # chars of full-function source per function
MAXTOTAL = 60000     # chars of extracted full source per record
IDENT = re.compile(r'^[A-Za-z_]\w*$')

SYS = r'''You repair annotations of C and C++ kernel functions. An earlier tool wrote them and independent checkers rejected them (or could not check them); the failure history is given. For each listed function, read the real code and write a CORRECT annotation based on that code. Reply with ONE JSON object and nothing else:
{"functions":[{"idx":int (copy it),"name":str,"action":"fix" or "drop","prose_contract":str,"contract":str,"note":str}]}
Rules:
- Reply with one entry per listed function. "drop" only if the listed item is not a function defined in this code (a macro that defines no function, a declaration, a fragment); never drop only because the head is cut off: the full source of such functions is given. A drop needs a one-sentence reason in note.
- name: the real function name as defined in the code. C++: Class::method or operator<<, without the parameter list. If the function is GENERATED by a macro (SYSCALL_DEFINEn, BPF_CALL_n, DEFINE_*/ASAN_*/CSAN_*-style generator macros) and its real name does not occur literally in the file, set name to the exact macro invocation text as written in the source (for example ASAN_BUS_READ_FUNC(, 1, uint8_t) or ATOMIC64_EMU_BIN(add, void, (*p = *p + v), return)); put the generated function name in the first words of the prose ("Generated function kasan_bus_space_read_1(tag, hnd, offset)."). A macro template whose arguments are placeholders is named by its invocation form as well. Say in note that the name is a macro invocation.
- prose_contract: the precondition and the postcondition, one plain sentence each, covering EVERY return value and error code the code can produce and any lock, reference or memory the caller gets or loses. It must be exactly true of the code: state nothing the code does not do, leave out nothing it does. Base it on the full source, not on the old prose.
- contract: ONLY for a function whose parameters and return value are all integers, booleans or enums; otherwise "". Exactly one line: /*@ requires <C expression>; ensures <C expression>; */
  * use only the parameter names and the word result (not \result) for the return value; no calls to functions or macros, no struct fields, no pointers, no words;
  * logic: && || ! ==> (implies) <==> (if and only if) ?: and the C comparison and arithmetic operators; numbers in decimal or hex; true is \true;
  * PARENTHESISE bit operations: write result == (x & 3), never result == x & 3;
  * integers are mathematical: if the code can overflow or wrap (a + 1, x << n, a * b), the requires must exclude those inputs (for example a < 2147483647, n < 32);
  * the ensures must be TRUE for every input that meets the requires, and must cover every return path (all error codes);
  * the requires must state only what the code needs; never write ensures \true.
- A formal contract that is WEAKER than the prose contract (it leaves out a return value, an error code or a condition the prose states), or that the code contradicts, is a defect. Strengthen it until it covers everything the prose says, or, when the formal language cannot say it, set contract to "" and make the prose complete and exactly true.
- The failure history is a claim to CHECK against the code, not an order: if it is wrong, keep the annotation but make it more precise. When you cannot write an annotation you are confident is correct, use action "drop" with the reason in note (it is then listed, not hidden).
- note: one short sentence, or "".'''


def find_end(lines, i0):
    """brace-balanced end (0-based, inclusive) of the construct whose first '{' is at or after line i0; None when no body starts within 6 lines."""
    depth = 0; started = False; inblk = False
    for i in range(i0, len(lines)):
        s = lines[i]; j = 0; n = len(s)
        while j < n:
            c = s[j]
            if inblk:
                if s.startswith('*/', j): inblk = False; j += 1
            elif s.startswith('/*', j): inblk = True; j += 1
            elif s.startswith('//', j): break
            elif c == '"' or c == "'":
                q = c; j += 1
                while j < n and s[j] != q:
                    if s[j] == '\\': j += 1
                    j += 1
            elif c == '{': depth += 1; started = True
            elif c == '}':
                depth -= 1
                if started and depth <= 0: return i
            j += 1
        if not started and i - i0 > 6: return None
    return None


def def_lines(lines, name):
    last = name.split('::')[-1].lstrip('~')
    if name.startswith('operator'):
        pat = re.compile(re.escape(last))
    else:
        pat = re.compile(r'(^|[^\w.>])' + re.escape(name if '::' in name else last) + r'\s*\(')
    out = []
    for i, s in enumerate(lines):
        if not s or s[0] in ' \t#}*/' or s.rstrip().endswith(';') or s.startswith('return'): continue
        if pat.search(s): out.append(i)
    return out


def extract(lines, name, s, e):
    """(first, last) 0-based line range of the function NAME in the file, or None."""
    plain = IDENT.match(name) or '::' in name or name.startswith('operator')
    if plain:
        cands = def_lines(lines, name)
    else:
        mm = re.match(r'\s*(\w+)\s*\(\s*(\w*)', name)
        if not mm: return None
        pat = re.compile(r'(^|[^\w])' + re.escape(mm.group(1)) + r'\s*\(\s*' + re.escape(mm.group(2)))
        cands = [i for i, t in enumerate(lines) if pat.search(t) and not t.lstrip().startswith('#define')]
    best = None
    for i in cands:
        e0 = find_end(lines, i)
        if e0 is None: continue
        d = 0 if (s - 1 <= i <= e - 1) else min(abs(i - (s - 1)), abs(i - (e - 1)))
        if best is None or d < best[0]: best = (d, i, e0)
    if best is None:
        if cands and not plain:   # generator macro invocation without a body: a few lines of context
            i = cands[0]; return (i, min(len(lines) - 1, i + 12))
        return None
    _, i, e0 = best
    f = i
    while f > 0 and i - f < 4 and lines[f-1].strip() and not lines[f-1].rstrip().endswith((';', '}', '{', '*/')) and not lines[f-1].lstrip().startswith('#'): f -= 1
    return (f, e0)


def macro_def(lines, name):
    mm = re.match(r'\s*(\w+)\s*\(', name)
    if not mm: return None
    pat = re.compile(r'^\s*#\s*define\s+' + re.escape(mm.group(1)) + r'\b')
    for i, t in enumerate(lines):
        if pat.match(t):
            j = i
            while j < len(lines) - 1 and lines[j].rstrip().endswith('\\') and j - i < 60: j += 1
            return (i, j)
    return None


def main():
    rec = json.loads(sys.stdin.readline())
    f = rec['file']; s = rec['start']; e = rec['end']; src = rec['source']
    lines = None
    for cand in (f,):
        try:
            with open(cand, errors='replace') as fh: lines = fh.read().split('\n')
            break
        except Exception:
            pass
    full = []; total = 0
    if lines:
        seen = set()
        for fn in rec['functions']:
            nm = fn['name']
            if nm in seen: continue
            seen.add(nm)
            r = extract(lines, nm, s, e)
            if r:
                a, b = r
                if not (a >= s - 1 and b <= e - 1):   # not wholly inside the slice
                    body = '\n'.join(lines[a:b+1])
                    if len(body) > MAXFULL: body = body[:MAXFULL] + '\n... (truncated)'
                    if total + len(body) <= MAXTOTAL:
                        full.append('[full source of %s: lines %d-%d of %s]\n%s' % (nm, a+1, b+1, os.path.basename(f), body)); total += len(body)
            if not (IDENT.match(nm) or '::' in nm):
                md = macro_def(lines, nm)
                if md:
                    body = '\n'.join(lines[md[0]:md[1]+1])[:4000]
                    if total + len(body) <= MAXTOTAL:
                        full.append('[macro definition used by %s: lines %d-%d of %s]\n%s' % (nm, md[0]+1, md[1]+1, os.path.basename(f), body)); total += len(body)
    fl = []
    for fn in rec['functions']:
        fl.append('[#%d] %s (kind %s, status now: %s)\nfailure history: %s\ncurrent prose contract: %s\ncurrent formal contract: %s\n' % (
            fn['i'], fn['name'], fn.get('kind', ''), fn.get('status', ''), (fn.get('reasons') or '(none)')[:1500], fn.get('prose') or '(none)', fn.get('contract') or '(none)'))
    user = 'Source slice (lines %d-%d of %s):\n%s\n\n' % (s, e, f.split('/')[-1], src)
    if full:
        user += 'Full source from the real file (the slice does not contain these functions completely):\n' + '\n\n'.join(full) + '\n\n'
    user += 'Functions to fix:\n' + '\n'.join(fl)
    req = {'model': 'morph-dsv41flash-1017', 'messages': [{'role': 'system', 'content': SYS}, {'role': 'user', 'content': user}],
           'max_tokens': int(os.environ.get('DSV_MAXTOK') or '24000'), 'reasoning_effort': os.environ.get('DSV_EFFORT') or 'medium', 'temperature': 0.2}
    json.dump(req, sys.stdout)


main()
