#!/bin/bash
# mine.sh <run-id> <Model.lean> [Spec.lean]   Parse the theorems of a Lean model file into docs/plan/lib/mine.db (SQLite), classify them and
# the shape of each proof, and (with --report) write docs/plan/lib/MINED.md. Plain shell + awk + sqlite3: no Python (Odin's rule for shipped tools).
#   mine.sh --report            regenerate the report from the database
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); LIB=$HERE/../../lib; DB=$LIB/mine.db; mkdir -p "$LIB"
sqlite3 "$DB" "create table if not exists theorem(run text, name text, kind text, statement text, proof text, lines int, shape text, tactics text, primary key(run,name));
create table if not exists spec(run text, name text, statement text, primary key(run,name));"
report() {
  {
  echo "# Mined proof patterns (generated by tools/mine/mine.sh; do not edit by hand)"; echo
  echo "Runs mined: $(sqlite3 "$DB" "select group_concat(distinct run) from theorem")"; echo
  echo "## Proofs by shape"; echo; echo "| shape | locked statements | helpers | negations | median lines |"; echo "|---|---|---|---|---|"
  sqlite3 -separator ' | ' "$DB" "select '| '||shape, sum(kind='locked'), sum(kind='helper'), sum(kind='neg'), cast(avg(lines) as int)||' |' from theorem group by shape order by count(*) desc"
  echo; echo "## Tactic frequency (proofs that use the tactic)"; echo; echo "| tactic | proofs |"; echo "|---|---|"
  sqlite3 -separator ' | ' "$DB" "with t as (select name, run, value as tac from theorem, json_each('['||'\"'||replace(tactics,' ','\",\"')||'\"'||']') where tactics<>'') select '| '||tac, count(*)||' |' from t group by tac order by count(*) desc"
  echo; echo "## Every proof, by shape (statement, then proof)"; echo
  sqlite3 "$DB" "select distinct shape from theorem order by shape" | while IFS= read -r s; do
    echo "### $s"; echo
    sqlite3 -separator $'\x1f' "$DB" "select name, kind, statement, proof from theorem where shape='$s' order by run, name" | while IFS=$'\x1f' read -r n k st pr; do
      echo "- \`$n\` ($k): \`$st\`"; echo '  ```lean'; echo "$pr" | tr $'\x1e' '\n' | sed 's/^/  /'; echo '  ```'
    done; echo
  done
  } > "$LIB/MINED.md"
  echo "wrote $LIB/MINED.md"
}
if [ "${1:-}" = "--report" ]; then report; exit 0; fi
RUN=$1; MODEL=$2; SPEC=${3:-}
sqlite3 "$DB" "delete from theorem where run='$RUN'; delete from spec where run='$RUN';"
# locked statement names = the 'def <name> : Prop' lines of the spec (parameterless statements)
LOCKED=""
if [ -n "$SPEC" ]; then
  LOCKED=$(sed -n "s/^def \([A-Za-z_0-9']*\) *: *Prop.*/\1/p" "$SPEC" | tr '\n' ' ')
  awk -v run="$RUN" 'function q(s){gsub(/\047/,"\047\047",s);return "\047" s "\047"}
    /^def [A-Za-z_0-9]+ *: *Prop/ {if(n)print "insert or replace into spec values(" q(run) "," q(n) "," q(b) ");"; n=$2; b=$0; next}
    n && /^(def|theorem|structure|inductive|end|namespace|abbrev)/ {print "insert or replace into spec values(" q(run) "," q(n) "," q(b) ");"; n=""}
    n {b=b " " $0} END{if(n)print "insert or replace into spec values(" q(run) "," q(n) "," q(b) ");"}' "$SPEC" | sqlite3 "$DB"
fi
awk -v run="$RUN" -v locked=" $LOCKED " '
function q(s){gsub(/\047/,"\047\047",s);return "\047" s "\047"}
function flush(   st,pr,kind,shape,tac,i,words,w,seen,nl,rest){
  if(name=="")return
  i=index(blk,":="); if(i==0){st=blk; pr=""} else {st=substr(blk,1,i-1); pr=substr(blk,i+2)}
  gsub(/[ \t]+/," ",st); gsub(/^ +| +$/,"",st)
  kind="helper"; if(index(locked," " name " ")>0) kind="locked"; else if(name ~ /^neg_/) kind="neg"
  tac=""; nl=split(prl,words,"\n")
  # tactic vocabulary found in the proof text
  split("rfl omega simp simp_all constructor cases rcases obtain have exact absurd intro intros subst linarith aesop decide norm_num contradiction rw unfold ext funext by_contra push_neg exists refine apply calc induction Finset.mem_biUnion Finset.inter_subset_left Nat.lt_succ_self", vocab, " ")
  for(w in vocab){ if(index(pr, vocab[w])>0) tac=tac (tac==""?"":" ") vocab[w] }
  shape="other"
  if(pr ~ /Finset\.mem_biUnion/ && pr ~ /cases/) shape="biUnion + case split over an enum"
  else if(pr ~ /omega/ && pr ~ /have/) shape="have projections, then omega"
  else if(pr ~ /omega/) shape="omega"
  else if(pr ~ /rcases|obtain/ ) shape="destructure and rebuild"
  else if(pr ~ /^[ \n]*by[ \n]+(intro[^\n]*\n[ \n]*)*(exact )?(rfl|⟨rfl, *rfl⟩)[ \n]*$/) shape="intro, then rfl (definitional)"
  else if(pr ~ /exact Finset\.|exact Nat\.|exact Set\./) shape="intro, then one library lemma"
  else if(pr ~ /rfl/ && prl <= 4) shape="intro, then rfl (definitional)"
  gsub(/\n/,"\036",pr)
  print "insert or replace into theorem values(" q(run) "," q(name) "," q(kind) "," q(st) "," q(pr) "," nlines "," q(shape) "," q(tac) ");"
}
/^(theorem|lemma) / { flush(); name=$2; sub(/[:(].*$/,"",name); blk=$0; prl=1; nlines=1; next }
/^(end |namespace |import |open |\/\-\-|\/\-)/ { if(name!=""){flush(); name=""; blk=""}; next }
name!="" { blk=blk "\n" $0; prl++; nlines++ }
END{flush()}' "$MODEL" | sqlite3 "$DB"
sqlite3 "$DB" "select '$RUN: '||count(*)||' theorems ('||sum(kind='locked')||' locked, '||sum(kind='helper')||' helper, '||sum(kind='neg')||' negations)' from theorem where run='$RUN'"
