"""Check every app spec under Apps/ and write Apps/INDEX.md.

Checks, per app directory Apps/<category>/<slug>/:
  1. SPEC.md and manifest.json exist; the manifest parses and its id is org.pbsd.<slug>.
  2. SPEC.md has the 13 numbered sections of SPEC_TEMPLATE.md.
  3. The app ID in the spec header is in CATALOGUE.md with the same slug.
  4. Feature IDs (<APPID>-Fnnn) and work-item IDs (<APPID>-Wnn) are defined once each.
  5. Every platform gap reference G-nn exists in PLATFORM.md.
Also reports catalogue entries that have no spec yet.

Exit 0 when clean, 1 on any problem.  Usage: python3 Apps/00-foundation/tools/build_index.py [--check]
(--check does not rewrite INDEX.md).
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

APPS = Path(__file__).resolve().parents[2]
FOUNDATION = APPS / "00-foundation"
SECTIONS = [
    "Purpose", "Scope", "Users and top tasks", "Features", "GUI", "Architecture",
    "Security and privacy", "Settings", "Accessibility and languages",
    "Performance budgets", "Testing and proof", "Build plan", "Open questions and risks",
]
CAT_ROW = re.compile(r"^\| ([A-Z]{2}\d{2}) \| `([a-z0-9-]+)` \| ([^|]+) \| .* \| (P\d) \|$")


def catalogue() -> dict[str, dict]:
    out, category = {}, ""
    for line in (FOUNDATION / "CATALOGUE.md").read_text().splitlines():
        if line.startswith("## "):
            category = line[3:].split(" ")[0]
        m = CAT_ROW.match(line)
        if m:
            out[m.group(1)] = {"slug": m.group(2), "name": m.group(3).strip(),
                               "priority": m.group(4), "category": category}
    return out


def defined_ids(text: str, appid: str, kind: str) -> Counter:
    """IDs defined as the first cell of a table row, or as a list item."""
    pat = re.compile(rf"^(?:\|\s*|[-*]\s+\**)`?({appid}-{kind}\d+)`?\**\s*(?:\||[:—-]|\s)", re.M)
    return Counter(pat.findall(text))


def main() -> int:
    cat = catalogue()
    gaps = set(re.findall(r"^\| (G-\d+) \|", (FOUNDATION / "PLATFORM.md").read_text(), re.M))
    by_slug = {(v["category"], v["slug"]): k for k, v in cat.items()}
    problems: list[str] = []
    rows = []
    seen = set()

    for manifest in sorted(APPS.glob("*/*/manifest.json")):
        d = manifest.parent
        category, slug = d.parent.name, d.name
        rel = f"{category}/{slug}"
        appid = by_slug.get((category, slug))
        if appid is None:
            problems.append(f"{rel}: not in CATALOGUE.md")
            continue
        seen.add(appid)
        try:
            man = json.loads(manifest.read_text())
        except json.JSONDecodeError as e:
            problems.append(f"{rel}: manifest.json does not parse: {e}")
            man = {}
        if man and man.get("id") != f"org.pbsd.{slug}":
            problems.append(f"{rel}: manifest id {man.get('id')!r} is not org.pbsd.{slug}")
        spec = d / "SPEC.md"
        if not spec.exists():
            problems.append(f"{rel}: SPEC.md missing")
            continue
        text = spec.read_text()
        if f"`{appid}`" not in text[:1500]:
            problems.append(f"{rel}: header does not state ID `{appid}`")
        for n, title in enumerate(SECTIONS, 1):
            if not re.search(rf"^## {n}\. {re.escape(title)}\s*$", text, re.M):
                problems.append(f"{rel}: section '## {n}. {title}' missing")
        feats = defined_ids(text, appid, "F")
        works = defined_ids(text, appid, "W")
        for kind, c in (("feature", feats), ("work item", works)):
            dup = sorted(k for k, v in c.items() if v > 1)
            if dup:
                problems.append(f"{rel}: duplicate {kind} IDs: {', '.join(dup[:8])}")
        if not feats:
            problems.append(f"{rel}: no feature rows found")
        for g in sorted(set(re.findall(r"\bG-\d+\b", text)) - gaps):
            problems.append(f"{rel}: unknown platform gap {g}")
        caps = man.get("capabilities", []) if man else []
        rows.append((appid, cat[appid]["name"], rel, cat[appid]["priority"], text.count("\n") + 1,
                     len(feats), len(works), len(caps),
                     ", ".join(man.get("backing_repos", []) or []) if man else ""))

    missing = [k for k in cat if k not in seen]
    rows.sort()
    lines = [
        "<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->",
        "# App index",
        "",
        "By Odin Loch",
        "",
        "Generated by `python3 Apps/00-foundation/tools/build_index.py`. Do not edit by hand.",
        "",
        f"Specs: {len(rows)} of {len(cat)} catalogue apps. "
        f"Features: {sum(r[5] for r in rows)}. Work items: {sum(r[6] for r in rows)}. "
        f"Spec lines: {sum(r[4] for r in rows)}.",
        "",
        "| ID | App | Spec | Pri | Lines | Features | Work items | Capabilities | Backing repos |",
        "|---|---|---|---|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        lines.append(f"| {r[0]} | {r[1]} | [{r[2]}]({r[2]}/SPEC.md) | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} | {r[8]} |")
    lines += ["", "## By priority", "", "| Priority | Apps | Features |", "|---|---:|---:|"]
    for p in sorted({r[3] for r in rows}):
        sel = [r for r in rows if r[3] == p]
        lines.append(f"| {p} | {len(sel)} | {sum(r[5] for r in sel)} |")
    lines += ["", "## Catalogue entries without a spec", ""]
    lines += [f"- {k} {cat[k]['name']}" for k in missing] or ["None."]
    lines += ["", "## Check result", ""]
    lines += [f"- {p}" for p in problems] or ["No problems found."]
    if "--check" not in sys.argv:
        (APPS / "INDEX.md").write_text("\n".join(lines) + "\n")
    for p in problems:
        print("PROBLEM", p)
    print(f"{len(rows)}/{len(cat)} specs, {sum(r[5] for r in rows)} features, "
          f"{sum(r[6] for r in rows)} work items, {len(problems)} problem(s), {len(missing)} without spec")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
